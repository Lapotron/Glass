import { promises as fs } from 'node:fs';
import { markdownCatalog, authoringVersion, codeMetadata } from '../src/shared/markdown-catalog.js';
import { chartStyles } from '../src/shared/chart-schema.js';
import { chartExample } from '../src/shared/chart-examples.js';
import { pseudocodeSnippets, quicksortAlgorithm } from '../src/shared/pseudocode-authoring.js';
import { mermaidExamples, mermaidVersion } from '../src/shared/mermaid-authoring.js';
import {
  mathCommandCatalog,
  mathCommandSource,
  mathExtensions,
  mathEnvironments,
} from '../src/shared/math-authoring.js';
const reference = [
  `# Markdown component reference\n\nDialect: \`${authoringVersion}\`. Generated by \`npm run authoring:docs\` from the shared catalog. Read [the authoring guide](authoring.md) for ordinary Markdown and [charts](charts.md) for interactive data.\n`,
];
reference.push(
  '## Code fence metadata\n\nBuild-time Expressive Code. See [reader upgrades](reader-upgrades.md#code-blocks).\n\n| Option | Example | Behavior |\n| --- | --- | --- |\n' +
    codeMetadata
      .map((item) => `| ${item.label} | \`${item.apply}\` | ${item.detail} |`)
      .join('\n') +
    '\n',
);
reference.push('## Pseudocode source snippets\n\nUse `pseudocode`, `pseudo` or `algorithm` fences. Source editing provides completion, linked snippet fields, block folding and matching. Accepted snippets insert END statements; ordinary typing does not. Inline source previews are disabled; Split/Preview and static output retain academic rendering. Built-ins are notation, never executed. See [pseudocode](pseudocode.md).\n');
for (const item of pseudocodeSnippets) reference.push(`### ${item.name}\n\n${item.description}.\n\n\`\`\`pseudocode\n${item.source.replaceAll('\t','  ')}\n\`\`\`\n`);
for (const c of markdownCatalog) {
  reference.push(
    `## ${c.name}\n\n${c.description}\n\nForm: ${c.kind}. Group: ${c.group}.${c.counter ? ` An explicit #id enables the ${c.counter} counter.` : ''}${c.children ? ` Allowed direct children: ${c.children.join(', ')}.` : ''}\n`,
  );
  if (Object.keys(c.attributes).length)
    reference.push(
      '| Attribute | Meaning | Values |\n| --- | --- | --- |\n' +
        Object.entries(c.attributes)
          .map(
            ([k, v]) =>
              `| ${k === 'id' ? '#id' : k} | ${v.description} | ${v.values?.join(', ') || 'text'} |`,
          )
          .join('\n') +
        '\n',
    );
  reference.push('`````markdown\n' + c.example.trimEnd() + '\n`````\n');
}
await fs.writeFile('docs/markdown-reference.md', reference.join('\n'));
await fs.writeFile(
  'docs/math-reference.md',
  [
    '# Math command reference\n\nGenerated by `npm run authoring:docs` from the shared MathJax 4 capability catalog. Read [math authoring](math-authoring.md) for package settings, preview behavior and compatibility. Core packages: base, ams, newcommand.\n',
    'Optional packages: ' +
      mathExtensions.map((name) => '`' + name + '`').join(', ') +
      '. Physics remains per-article opt-in.\n',
    '| Command | Package | Meaning | Example |\n| --- | --- | --- | --- |',
    ...mathCommandCatalog.map(
      (command) =>
        `| \`\\${command.name}\` | ${command.package || 'core'} | ${command.description} | \`${mathCommandSource(command).replaceAll('|', '\\|').replaceAll('\n', ' ')}\` |`,
    ),
    '\n## Environments\n\n' +
      mathEnvironments.map((name) => '`' + name + '`').join(', ') +
      '. Mathtools additionally enables its supported starred matrices and cases variants.\n',
  ].join('\n'),
);
const examples = [
  '# Chart examples\n\nGenerated from the validated chart examples by `npm run authoring:docs`. Each block is ready to paste into an article. See [chart options and interactions](../charts.md).\n',
];
for (const style of chartStyles) {
  const c = chartExample(style);
  const clean: any = { type: c.type, style: c.style, title: c.title };
  if (c.labels.length) clean.labels = c.labels;
  if (c.series.length)
    clean.series = c.series.map((s) => ({
      name: s.name,
      ...(s.values ? { values: s.values } : {}),
      ...(s.points ? { points: s.points } : {}),
      ...(s.style ? { style: s.style } : {}),
    }));
  for (const key of ['tree', 'nodes', 'links', 'cells', 'yLabels'] as const)
    if (c[key].length) clean[key] = c[key];
  if (['line', 'area', 'bar', 'scatter', 'bubble', 'mixed'].includes(style)) clean.zoom = true;
  examples.push(`## ${style}\n\n\`\`\`interactive\n${JSON.stringify(clean, null, 2)}\n\`\`\`\n`);
}
await fs.mkdir('docs/authoring-templates', { recursive: true });
await fs.writeFile('docs/authoring-templates/mermaid-diagrams.md',
  '---\nid: mermaid-diagrams-template\nslug: mermaid-diagrams-template\ntitle: Mermaid diagrams with transparent presentation\npublishedAt: 2026-10-23\nstatus: draft\n---\n\n' +
  `Mermaid ${mermaidVersion} compiles these self-contained examples to transparent light/dark SVG. Add accessible titles/descriptions when adapting them. The default node treatment stays quiet; authored colors and data encodings are retained. Read diagrams.md in the authoring pack for the viewing and export contract.\n\n` +
  mermaidExamples.map(example=>`## ${example.name}\n\n\`\`\`mermaid\n${example.source}\n\`\`\`\n`).join('\n'));
await fs.writeFile('docs/authoring-templates/pseudocode-sort.md',
  '---\nid: quicksort-template\nslug: quicksort-template\ntitle: Quicksort with inclusive bounds\npublishedAt: 2026-10-23\nstatus: draft\n---\n\n' +
  '## Contract\n\nUse a zero-indexed array with inclusive `lo` and `hi` bounds. The base guard handles empty and single-element ranges. Lomuto partition places the final pivot and returns its index. This example is explanatory notation and is never executed by Glass.\n\n' +
  quicksortAlgorithm + '\nThe partition in :ref[alg-quicksort] keeps values no greater than the pivot on its left. The algorithm is in-place and is not stable; the final-element pivot can produce quadratic worst-case time. Rename the label when combining this template with another algorithm.\n');
await fs.writeFile('docs/authoring-templates/chart-examples.md', examples.join('\n'));
