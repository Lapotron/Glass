import { t } from '../shared/i18n.js';
import { StateEffect, StateField } from '@codemirror/state';
import { Decoration, EditorView, WidgetType, type DecorationSet } from '@codemirror/view';
import type { SourceMath } from './source-analysis.js';
import type { MathPreviewResult } from '../shared/math-preview.js';

export type SourceMathPreview = SourceMath & { result?: MathPreviewResult; visible?: boolean };
export const mathPreviewUpdate = StateEffect.define<SourceMathPreview[]>();
class MathWidget extends WidgetType {
  constructor(readonly preview: SourceMathPreview) {
    super();
  }
  eq(other: MathWidget) {
    return (
      this.preview.source === other.preview.source &&
      this.preview.display === other.preview.display &&
      this.preview.result?.html === other.preview.result?.html &&
      this.preview.result?.error === other.preview.result?.error
    );
  }
  get estimatedHeight() {
    return this.preview.display ? 96 : -1;
  }
  toDOM(view: EditorView) {
    const wrapper = document.createElement(this.preview.display ? 'div' : 'span'),
      body = document.createElement(this.preview.display ? 'div' : 'span');
    wrapper.className = this.preview.display ? 'source-math-widget' : 'source-math-inline';
    wrapper.setAttribute(
      'aria-label',
      this.preview.display ? t('Display math preview') : t('Inline math preview'),
    );
    body.className = this.preview.display ? 'source-math-preview' : 'source-math-inline-body';
    if (this.preview.result?.html) {
      // SVG is generated by the local restricted MathJax renderer, never arbitrary Markdown HTML.
      body.innerHTML = this.preview.result.html;
    } else {
      body.classList.add('source-math-message');
      body.textContent = this.preview.display
        ? this.preview.result?.error || 'Rendering equation…'
        : this.preview.result?.error
          ? t('Invalid math')
          : '…';
      body.setAttribute('role', 'status');
      if (this.preview.result?.error) {
        wrapper.dataset.error = 'true';
        wrapper.title = this.preview.result.error;
        if (this.preview.display) {
          const retry = document.createElement('button');
          retry.type = 'button';
          retry.className = 'text-link';
          retry.textContent = t('Retry preview');
          retry.onclick = () => view.dom.dispatchEvent(new Event('studio-retry-math'));
          body.append(retry);
        }
        if (!this.preview.display) {
          wrapper.tabIndex = 0;
          wrapper.setAttribute('aria-label', this.preview.result.error);
        }
      }
    }
    wrapper.append(body);
    requestAnimationFrame(() => {
      if (wrapper.isConnected) view.requestMeasure();
    });
    return wrapper;
  }
  ignoreEvent() {
    return true;
  }
}
export const sourceMathPreviews = StateField.define<{
  previews: SourceMathPreview[];
  decorations: DecorationSet;
}>({
  create: () => ({ previews: [], decorations: Decoration.none }),
  update(value, transaction) {
    if (transaction.docChanged) {
      // A changed macro can affect later equations. Keep untouched geometry but discard their drawing.
      const changedMath = value.previews.some((math) =>
        transaction.changes.touchesRange(math.from, math.to),
      );
      value = {
        ...value,
        previews: value.previews
          .filter((math) => !transaction.changes.touchesRange(math.from, math.to))
          .map((math) => ({
            ...math,
            from: transaction.changes.mapPos(math.from),
            to: transaction.changes.mapPos(math.to),
            result: changedMath ? undefined : math.result,
          })),
      };
    }
    for (const effect of transaction.effects)
      if (effect.is(mathPreviewUpdate)) value = { ...value, previews: effect.value };
    if (
      !transaction.docChanged &&
      !transaction.effects.some((effect) => effect.is(mathPreviewUpdate))
    )
      return value;
    return {
      ...value,
      decorations: Decoration.set(
        value.previews
          .filter(
            (math) =>
              math.visible !== false &&
              math.result?.html !== '' &&
              math.to <= transaction.newDoc.length,
          )
          .map((math) =>
            Decoration.widget({ widget: new MathWidget(math), side: 1, block: math.display }).range(
              math.display ? transaction.newDoc.lineAt(math.to).to : math.to,
            ),
          ),
        true,
      ),
    };
  },
  provide: (field) => EditorView.decorations.from(field, (value) => value.decorations),
});
