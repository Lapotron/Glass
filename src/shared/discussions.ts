/** Read only supported public attributes. Snippets are never inserted into the DOM. */
export function readGiscusSnippet(snippet: string): Partial<DiscussionConfig> {
  if (snippet.length > 32768) throw new Error('Use a Giscus embed snippet under 32 KB.');
  const tag = snippet.match(/<(?:script|giscus-widget)\b[^>]*>/i)?.[0];
  if (!tag) throw new Error('Paste the script or web component generated by giscus.app.');
  const attrs = new Map<string, string>();
  for (const match of tag.matchAll(/([\w-]+)\s*=\s*(["'])(.*?)\2/gs))
    attrs.set(
      match[1]
        .toLowerCase()
        .replace(/^data-/, '')
        .replaceAll('-', ''),
      match[3],
    );
  if (/^<script/i.test(tag) && attrs.get('src') !== 'https://giscus.app/client.js')
    throw new Error('This is not a Giscus embed snippet.');
  const patch: Partial<DiscussionConfig> = {};
  for (const [attribute, key] of [
    ['repo', 'repo'],
    ['repoid', 'repoId'],
    ['category', 'category'],
    ['categoryid', 'categoryId'],
  ] as const)
    if (attrs.has(attribute)) patch[key] = attrs.get(attribute)!;
  if (!patch.repo || !patch.repoId || !patch.categoryId)
    throw new Error('The snippet needs a repository, repository ID, and category ID.');
  if (attrs.has('reactionsenabled')) patch.reactions = attrs.get('reactionsenabled') === '1';
  if (attrs.has('emitmetadata')) patch.showMetadata = attrs.get('emitmetadata') === '1';
  if (attrs.get('inputposition') === 'top' || attrs.get('inputposition') === 'bottom')
    patch.inputPosition = attrs.get('inputposition') as 'top' | 'bottom';
  const lang = attrs.get('lang');
  if (discussionLanguages.some((value) => value === lang))
    patch.language = lang as DiscussionConfig['language'];
  // Keep the site's coordinated material for pasted custom CSS and unsupported provider themes.
  const theme = attrs.get('theme');
  if (discussionThemes.some((value) => value === theme))
    patch.theme = theme as DiscussionConfig['theme'];
  patch.enabled = true;
  return patch;
}

export function builtInDiscussionTheme(config: DiscussionConfig, dark: boolean) {
  return config.theme === 'site' ? (dark ? 'transparent_dark' : 'light') : config.theme;
}
